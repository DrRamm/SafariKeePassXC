// Pick the first preferred system language that the app ships, falling back
// to English. Region subtags are dropped ("pt-BR" -> "pt").
function detectLanguage() {
    const candidates = [];
    if (typeof navigator !== "undefined") {
        if (Array.isArray(navigator.languages)) candidates.push(...navigator.languages);
        if (navigator.language) candidates.push(navigator.language);
    }
    for (const candidate of candidates) {
        const base = String(candidate).toLowerCase().split(/[-_]/)[0];
        if (Object.prototype.hasOwnProperty.call(translations, base)) return base;
    }
    return "en";
}

const language = detectLanguage();

function t(key) {
    return translations[language][key] ?? translations.en[key] ?? key;
}

function localizeDocument() {
    document.documentElement.lang = language;
    document.documentElement.dir = /^(ar|fa|he|ur)$/.test(language) ? "rtl" : "ltr";
    for (const element of document.querySelectorAll("[data-i18n]")) {
        element.innerHTML = t(element.dataset.i18n);
    }
}

function showUpdate({ version, url }) {
    if (typeof version !== "string" || typeof url !== "string") return;
    const banner = document.querySelector("#update-banner");
    if (!banner) return;
    document.querySelector("#update-version").textContent = version;
    banner.dataset.url = url;
    banner.hidden = false;
}

function hideUpdate() {
    const banner = document.querySelector("#update-banner");
    if (!banner) return;
    banner.hidden = true;
    banner.dataset.url = "";
}

function show(enabled, useSettingsInsteadOfPreferences) {
    if (typeof enabled === "boolean") {
        document.body.classList.toggle(`state-on`, enabled);
        document.body.classList.toggle(`state-off`, !enabled);
    } else {
        document.body.classList.remove(`state-on`);
        document.body.classList.remove(`state-off`);
    }
}

function openPreferences() {
    webkit.messageHandlers.controller.postMessage("open-preferences");
}

localizeDocument();
document.querySelector("button.open-preferences").addEventListener("click", openPreferences);

document.querySelector("#update-open").addEventListener("click", () => {
    const url = document.querySelector("#update-banner").dataset.url;
    if (!url) return;
    webkit.messageHandlers.controller.postMessage("open-release-url:" + url);
});
