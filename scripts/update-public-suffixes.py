#!/usr/bin/env python3
"""Regenerate the public suffix data used by background.js.

The extension validates WebAuthn RP IDs against the Public Suffix List. Only
the rules that matter for that check are kept: multi-label exact suffixes,
wildcard bases and exceptions. Single-label TLDs are handled by the validator.

Usage:
    python3 scripts/update-public-suffixes.py
"""

from __future__ import annotations

import json
import pathlib
import urllib.request

PSL_URL = "https://publicsuffix.org/list/public_suffix_list.dat"
OUTPUT = (
    pathlib.Path(__file__).resolve().parent.parent
    / "SafariKeePassXC Extension"
    / "Resources"
    / "public-suffixes.js"
)


def main() -> None:
    with urllib.request.urlopen(PSL_URL, timeout=60) as response:
        text = response.read().decode("utf-8")

    rules = [
        line.strip()
        for line in text.splitlines()
        if line.strip() and not line.strip().startswith("//")
    ]

    exact = sorted(
        rule
        for rule in rules
        if not rule.startswith("*.") and not rule.startswith("!") and "." in rule
    )
    wildcards = sorted(rule[2:] for rule in rules if rule.startswith("*."))
    exceptions = sorted(rule[1:] for rule in rules if rule.startswith("!"))

    def js_string(value: str) -> str:
        return json.dumps(value, ensure_ascii=True)

    output = "\n".join(
        [
            "// Public Suffix List (https://publicsuffix.org/list/public_suffix_list.dat),",
            "// MPL-2.0. Generated by scripts/update-public-suffixes.py: do not edit by hand.",
            "//",
            "// Only rules that matter for WebAuthn RP ID validation are kept:",
            "// multi-label exact suffixes, wildcard bases and exceptions. Single-label",
            "// TLDs are treated as public suffixes by the validator itself.",
            "",
            f"export const PUBLIC_SUFFIXES = {js_string(chr(10).join(exact))};",
            "",
            f"export const PUBLIC_SUFFIX_WILDCARDS = {js_string(chr(10).join(wildcards))};",
            "",
            f"export const PUBLIC_SUFFIX_EXCEPTIONS = {js_string(chr(10).join(exceptions))};",
            "",
        ]
    )

    OUTPUT.write_text(output, encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(output)} bytes)")


if __name__ == "__main__":
    main()
